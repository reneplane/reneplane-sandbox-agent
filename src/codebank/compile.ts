/**
 * Compiling a codebank: for every problem and stack, the learner's starter bundle and the grader's
 * bundle, plus what the platform's catalog shows. Hidden tests only ever go into grader bundles.
 *
 *   starter.tar.gz   manifest.json, repo.bundle (curated history → tag reneplane-start),
 *                    workspace.yaml, template.sql (SQL Server)
 *   grader.tar.gz    manifest.json, repo.bundle, grade.yaml, hidden/ (+ hidden/index.json),
 *                    reference.patch, reference.sql (SQL problems), template.sql (SQL Server)
 */

export interface FileRef {
  /** Relative to the release folder */
  file: string;
  sha256: string;
  size: number;
}

export interface CompiledVariant {
  variant: string;
  label: string;
  engine: string;
  requires: string[];
  /** Services the variant needs from Reneplane (SQL Server comes from the pool) */
  remote: string[];
  minAgentVersion: string;
  starterCommit: string;
  starter: FileRef;
  grader: FileRef;
  template: FileRef | null;
  /** The reference as a learner-shaped patch: shown to a learner after they submit */
  reference: FileRef;
  /** Paths the reference changes, for the report */
  referenceChanges: string[];
}

export interface CompiledProblem {
  id: string;
  slug: string;
  kind: 'app' | 'sql';
  type: string;
  title: string;
  difficulty: string;
  skills: string[];
  brief: string;
  variants: CompiledVariant[];
}

export interface ReleaseManifest {
  format: 1;
  codebank: string;
  name: string;
  release: string;
  commit: string;
  problems: CompiledProblem[];
}

export interface CompileContext {
  codebank: LoadedCodebank;
  git: Git;
  gitFor: (cwd: string) => Promise<Git>;
  /** Where intermediate trees and repos go (kept with --keep, for debugging) */
  work: string;
  onProgress?: (line: string) => void;
}

export function sha256File(path: string): string {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

/** Every file under a folder, as forward-slash relative paths */
export function walk(root: string): string[] {
  const out: string[] = [];
  const visit = (dir: string) => {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name);
      const stat = lstatSync(path);
      if (stat.isSymbolicLink()) continue;
      if (stat.isDirectory()) visit(path);
      else out.push(relative(root, path).split(sep).join('/'));
    }
  };
  if (existsSync(root)) visit(root);
  return out.sort();
}

/** Paths that differ between two trees (added, removed or changed) */
export function changedPaths(a: string, b: string): string[] {
  const left = new Set(walk(a));
  const right = new Set(walk(b));
  const changed: string[] = [];
  for (const path of new Set([...left, ...right])) {
    if (!left.has(path) || !right.has(path)) changed.push(path);
    else if (!readFileSync(join(a, path)).equals(readFileSync(join(b, path)))) changed.push(path);
  }
  return changed.sort();
}

function readWorkspaceIn(tree: string): { text: string; parsed: WorkspaceFile } {
  const file = join(tree, '.reneplane', 'workspace.yaml');
  if (!existsSync(file)) throw new Error('.reneplane/workspace.yaml is missing from the stack');
  const text = readFileSync(file, 'utf8');
  return { text, parsed: parseWorkspace(text) };
}

/**
 * The SQL Server template the pool loads into a leased database: the migrations as a script (made by
 * the stack's own tool, e.g. dotnet ef) or listed SQL files, then the seed. Built from the starter,
 * so it always matches what the learner starts with.
 */
export async function buildTemplate(stack: StackSpec, tree: string, workspace: WorkspaceFile, work: string, onProgress?: (line: string) => void): Promise<string> {
  const recipe = stack.template;
  if (!recipe) throw new Error('This stack has no template recipe');
  const parts: string[] = ['-- Generated by reneplane-local codebank compile: the starting schema, then the seed. Do not edit.'];
  if ('files' in recipe) {
    for (const file of recipe.files) parts.push(readFileSync(join(tree, ...file.split('/')), 'utf8').trim());
  } else {
    // Run in a copy: the tool writes build output we don't want anywhere else
    const copy = join(work, 'template-build');
    rmSync(copy, { recursive: true, force: true });
    cpSync(tree, copy, { recursive: true });
    const out = join(work, 'template-migrations.sql');
    const runtimes = await Promise.all(runtimesFor(packsFor(workspace)).map((name) => ensureRuntime(name)));
    const env = buildEnv(
      runtimes.flatMap((runtime) => runtime.path),
      Object.assign({}, ...runtimes.map((runtime) => runtime.env), recipe.env),
    );
    onProgress?.('  scripting the migrations for SQL Server');
    const result = await runCommand(shellCommand(render(recipe.run, { out: out.split('\\').join('/') })), {
      cwd: join(copy, ...recipe.cwd.split('/')),
      env,
      timeoutMs: 15 * 60_000,
      onLine: () => undefined,
    });
    if (result.code !== 0 || !existsSync(out)) throw new Error(`The template recipe failed (exit ${result.code}):\n${result.output.slice(-20).join('\n')}`);
    parts.push(readFileSync(out, 'utf8').replace(/^\uFEFF/, '').trim());
  }
  if (stack.seed && existsSync(join(tree, ...stack.seed.split('/')))) parts.push(readFileSync(join(tree, ...stack.seed.split('/')), 'utf8').trim());
  return `${parts.join('\nGO\n\n')}\nGO\n`;
}

/** The hidden suite's index: what the runner may know about it without importing it */
async function hiddenIndex(suite: string, kind: 'app' | 'sql'): Promise<unknown> {
  const script =
    kind === 'app'
      ? "const m = await import(process.argv[1]); console.log(JSON.stringify((m.behaviours ?? []).map(({ id, name, category, layer }) => ({ id, name, category, layer }))))"
      : "const m = await import(process.argv[1]); console.log(JSON.stringify((m.datasets ?? []).map(({ id, name, category }) => ({ id, name, category }))))";
  const result = await runFile(process.execPath, ['--input-type=module', '-e', script, pathToFileURL(suite).href], { timeoutMs: 60_000 });
  if (result.code !== 0) throw new Error(`The hidden suite ${suite} doesn't load: ${result.stderr.trim().split('\n').slice(-3).join(' ')}`);
  const entries = JSON.parse(result.stdout) as { id?: string; name: string }[];
  if (!entries.length) throw new Error(`The hidden suite ${suite} exports no ${kind === 'app' ? 'behaviours' : 'datasets'}`);
  if (kind === 'app' && new Set(entries.map((entry) => entry.id)).size !== entries.length) throw new Error(`The hidden suite ${suite} has duplicate behaviour ids`);
  return { kind, entries };
}

function filesUnder(root: string, prefix: string): TarEntry[] {
  return walk(root).map((path) => ({ path: `${prefix}${path}`, data: readFileSync(join(root, path)) }));
}

export interface VariantWork {
  starter: Projection;
  reference: Projection;
  repoDir: string;
  bundle: string;
  referencePatch: string;
  workspace: WorkspaceFile;
  template: string | null;
}

/** Everything one problem × stack needs; returns the files it wrote to `out` */
export async function compileVariant(context: CompileContext, problem: LoadedProblem, stack: string, out: string, release: string): Promise<{ compiled: CompiledVariant; work: VariantWork }> {
  const { codebank, git } = context;
  const stackSpec = codebank.spec.stacks[stack]!;
  const work = join(context.work, problem.spec.id, stack);
  rmSync(work, { recursive: true, force: true });
  mkdirSync(work, { recursive: true });

  const starter = await project(git, codebank, stack, join(work, 'starter'), { problem, side: 'starter' });
  const reference = await project(git, codebank, stack, join(work, 'reference'), { problem, side: 'reference' });
  const changes = changedPaths(starter.dir, reference.dir);
  if (!changes.length) throw new Error(`${problem.spec.id} on ${stack}: the starter is the same as the reference`);

  const repo = await buildStarterRepo({
    git: context.gitFor,
    dir: join(work, 'repo'),
    branch: problem.spec.branch,
    historyDir: join(codebank.root, 'history', stack),
    head: problem.spec.history?.head,
    starter,
  });
  const repoGit = await context.gitFor(repo.dir);
  const leaks = await findLeaks(repoGit, reference, changes);
  if (leaks.length) throw new Error(`${problem.spec.id} on ${stack}: ${leaks.join('; ')}`);
  const bundle = join(work, 'repo.bundle');
  await writeBundle(repoGit, problem.spec.branch, bundle);

  // The reference as a learner would submit it: the working tree becomes the reference, diffed against the tag
  for (const entry of readdirSync(repo.dir)) if (entry !== '.git') rmSync(join(repo.dir, entry), { recursive: true, force: true });
  for (const entry of readdirSync(reference.dir)) cpSync(join(reference.dir, entry), join(repo.dir, entry), { recursive: true });
  const referencePatch = await repoGit.diffSince(START_TAG);

  const { text: workspaceText, parsed: workspace } = readWorkspaceIn(starter.dir);
  const template = stackSpec.engine === 'sqlserver' ? await buildTemplate(stackSpec, starter.dir, workspace, work, context.onProgress) : null;
  const requires = packsFor(workspace);

  const manifest = {
    format: 1,
    codebank: codebank.spec.id,
    release,
    problem: problem.spec.id,
    variant: stack,
    kind: problem.spec.kind,
    branch: problem.spec.branch,
    startCommit: repo.startCommit,
    requires,
    minAgentVersion: problem.spec.minAgentVersion,
  };
  const manifestEntry = { path: 'manifest.json', data: Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`) };
  const bundleEntry = { path: 'repo.bundle', data: readFileSync(bundle) };
  const templateEntries = template ? [{ path: 'template.sql', data: Buffer.from(template) }] : [];

  // The grader's instructions: the stack's build-and-run recipe plus this problem's rules
  const suite = join(codebank.root, ...problem.dir.split('/'), ...problem.spec.hidden.split('/'));
  if (!existsSync(suite)) throw new Error(`${problem.dir}/problem.yaml: hidden: ${problem.spec.hidden} doesn't exist`);
  const hiddenDir = dirname(suite);
  const suiteName = relative(hiddenDir, suite).split(sep).join('/');
  const allow = problem.spec.stacks[stack]!.allow;
  let grade: Record<string, unknown>;
  const extra: TarEntry[] = [];
  if (problem.spec.kind === 'app') {
    const stackGrade = loadStackGrade(codebank.root, stack);
    if (!stackGrade) throw new Error(`stacks/${stack}/.reneplane/grade.yaml is missing (the grader needs it to build ${stack})`);
    grade = { kind: 'app', engine: stackSpec.engine, ...stackGrade, allow, seed: template ? null : (stackSpec.seed ?? workspace.database.seed ?? null), template: template ? 'template.sql' : null, hidden: `hidden/${suiteName}` };
  } else {
    const step = workspace.test.find((candidate) => candidate.sql);
    if (!step?.sql) throw new Error(`${problem.spec.id} on ${stack}: the workspace has no SQL test step`);
    const answer = step.sql.answer;
    extra.push({ path: 'reference.sql', data: readFileSync(join(reference.dir, ...answer.split('/'))) });
    grade = {
      kind: 'sql',
      engine: stackSpec.engine,
      columns: problem.spec.sql!.columns,
      orderMatters: problem.spec.sql!.orderMatters,
      allow,
      answer,
      schema: workspace.database.schema ?? null,
      example: workspace.database.seed ?? null,
      template: template ? 'template.sql' : null,
      reference: 'reference.sql',
      datasets: `hidden/${suiteName}`,
    };
  }
  const index = await hiddenIndex(suite, problem.spec.kind);

  const variantOut = join(out, problem.spec.id, stack);
  mkdirSync(variantOut, { recursive: true });
  const starterFile = join(variantOut, 'starter.tar.gz');
  writeFileSync(starterFile, tarGz([manifestEntry, bundleEntry, { path: 'workspace.yaml', data: Buffer.from(workspaceText) }, ...templateEntries]));
  const graderFile = join(variantOut, 'grader.tar.gz');
  writeFileSync(
    graderFile,
    tarGz([
      manifestEntry,
      bundleEntry,
      { path: 'grade.yaml', data: Buffer.from(stringify(grade)) },
      { path: 'reference.patch', data: Buffer.from(referencePatch) },
      ...filesUnder(hiddenDir, 'hidden/'),
      { path: 'hidden/index.json', data: Buffer.from(`${JSON.stringify(index, null, 2)}\n`) },
      ...templateEntries,
      ...extra,
    ]),
  );
  const referenceFile = join(variantOut, 'reference.patch');
  writeFileSync(referenceFile, referencePatch);
  let templateRef: FileRef | null = null;
  if (template) {
    const templateFile = join(variantOut, 'template.sql');
    writeFileSync(templateFile, template);
    templateRef = fileRef(out, templateFile);
  }

  return {
    compiled: {
      variant: stack,
      label: stackSpec.label,
      engine: stackSpec.engine,
      requires,
      remote: stackSpec.engine === 'sqlserver' ? ['mssql-pool'] : [],
      minAgentVersion: problem.spec.minAgentVersion,
      starterCommit: repo.startCommit,
      starter: fileRef(out, starterFile),
      grader: fileRef(out, graderFile),
      template: templateRef,
      reference: fileRef(out, referenceFile),
      referenceChanges: changes,
    },
    work: { starter, reference, repoDir: repo.dir, bundle, referencePatch, workspace, template },
  };
}

function fileRef(root: string, file: string): FileRef {
  return { file: relative(root, file).split(sep).join('/'), sha256: sha256File(file), size: lstatSync(file).size };
}

/** Compile the whole codebank (or some problems/stacks) into `out`, with release.json describing it */
export async function compileRelease(context: CompileContext, out: string, options: { release: string; problems?: string[]; stacks?: string[] }): Promise<ReleaseManifest> {
  const { codebank, git } = context;
  mkdirSync(out, { recursive: true });
  const problems: CompiledProblem[] = [];
  for (const problem of codebank.problems) {
    if (options.problems && !options.problems.includes(problem.spec.id)) continue;
    const variants: CompiledVariant[] = [];
    for (const stack of Object.keys(problem.spec.stacks)) {
      if (options.stacks && !options.stacks.includes(stack)) continue;
      context.onProgress?.(`compiling ${problem.spec.id} on ${stack}`);
      variants.push((await compileVariant(context, problem, stack, out, options.release)).compiled);
    }
    const briefFile = join(codebank.root, ...problem.dir.split('/'), ...problem.spec.brief.split('/'));
    if (!existsSync(briefFile)) throw new Error(`${problem.dir}/problem.yaml: brief: ${problem.spec.brief} doesn't exist`);
    problems.push({
      id: problem.spec.id,
      slug: problem.spec.slug,
      kind: problem.spec.kind,
      type: problem.spec.type,
      title: problem.spec.title,
      difficulty: problem.spec.difficulty,
      skills: problem.spec.skills,
      brief: readFileSync(briefFile, 'utf8'),
      variants,
    });
  }
  const manifest: ReleaseManifest = {
    format: 1,
    codebank: codebank.spec.id,
    name: codebank.spec.name,
    release: options.release,
    commit: (await git.run(['rev-parse', 'HEAD'])).trim(),
    problems,
  };
  writeFileSync(join(out, 'release.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

export function scratch(prefix: string): string {
  return mkdtempSync(join(tmpdir(), prefix));
}
